from pathlib import Path
import torch
import torch.nn as nn
from monai.networks.nets import UNet
from monai.losses import DiceLoss
from config import cfg
class SemanticConsistencyModule(nn.Module):
    """
    A self-contained module that holds the Frozen Teacher and calculates Semantic Loss.
    """
    def __init__(self, device):
        super().__init__()
        self.device = device
        
        # 1. Define the Teacher Architecture 
        # (MUST match the architecture used in 'phase2_train_teacher.py' exactly)
        self.teacher = UNet(
            spatial_dims=3,
            in_channels=1,
            out_channels=1,
            channels=(32, 64, 128, 256, 512),
            strides=(2, 2, 2, 2),
            num_res_units=2,
            norm="instance",
        ).to(device)

        # 2. Load Weights
        weights_path = Path(cfg["run_dir"]).parent / cfg["ckpt_dir"] / cfg["teacher_filename"]
        print(f"Loading Teacher weights from {weights_path}...")
        state_dict = torch.load(weights_path, map_location=device)
        self.teacher.load_state_dict(state_dict)

        # 3. Freeze the Teacher (Crucial)
        self.teacher.eval()
        for param in self.teacher.parameters():
            param.requires_grad = False
            
        # 4. Define Internal Dice Loss
        # sigmoid=True because the teacher outputs raw logits
        self.dice_loss_func = DiceLoss(sigmoid=True, include_background=False)

    def forward(self, sCT_pred, gt_mask_patch):
        """
        Args:
            sCT_pred: (B, 1, D, H, W) - The Synthetic CT generated by your model
            gt_mask_patch: (B, 1, D, H, W) - The binary mask ground truth
        Returns:
            Scalar Loss value
        """
        # Ensure sCT matches the input size expected by teacher
        # (Should be fine if your generator output shape == patch size)

        # 1. Teacher Forward Pass
        # We use torch.no_grad() for weights, but we need gradients to flow back 
        # to the input (sCT_pred). The teacher is just a complex, differentiable function now.
        # Note: We do NOT use no_grad context manager here because that would 
        # block gradients flowing back to sCT_pred.
        # Instead, we rely on parameters.requires_grad=False set in __init__.
        
        teacher_logits = self.teacher(sCT_pred)

        # 2. Robust Dice Calculation
        # Check if the batch has any valid organs to calculate loss on
        # (Avoids NaN/Instability if patch is background-only)
        has_organ = gt_mask_patch.sum(dim=(1, 2, 3, 4)) > 10
        
        if has_organ.sum() == 0:
            # Return 0 with a gradient attachment to satisfy the graph
            return sCT_pred.sum() * 0.0

        # Compute loss only on relevant samples in the batch
        loss = self.dice_loss_func(
            teacher_logits[has_organ], 
            gt_mask_patch[has_organ]
        )
        
        return loss